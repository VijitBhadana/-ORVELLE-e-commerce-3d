"""
Trace the ORVELLE logo (brand-source/orvelle-logo.jpg) into SVG path data.

Writes src/lib/logoPaths.ts with three layers:
  mark.orange  - the orange swoosh of the monogram (fixed brand colour)
  mark.dark    - the black parts of the monogram (drawn in currentColor)
  word.dark    - the ORVELLE wordmark (drawn in currentColor)

Run:  python tools/trace_logo.py   (needs numpy, opencv-python, pillow)
Optional:  --preview out.png  renders the traced paths for a visual check.
"""
import argparse
import os

import cv2
import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "brand-source", "orvelle-logo.jpg")
OUT = os.path.join(ROOT, "src", "lib", "logoPaths.ts")

# crop boxes in source pixels (x0, y0, x1, y1), padded a little around the ink
MARK_BOX = (1034, 407, 1714, 848)
WORD_BOX = (705, 941, 2046, 1131)

UP = 4  # supersampling factor for smoother contours
EPS = 1.6  # simplification tolerance, in supersampled px


def alphas(rgb):
    """Soft coverage of the orange ink and the black ink for every pixel."""
    r, g, b = (rgb[..., i].astype(np.float32) for i in range(3))
    lum = 0.299 * r + 0.587 * g + 0.114 * b
    bg_lum, org_lum, blk_lum = 236.0, 107.0, 22.0
    bg_chroma, org_chroma = 38.0, 175.0
    o = np.clip((r - b - bg_chroma) / (org_chroma - bg_chroma), 0, 1)
    k = np.clip((bg_lum - lum) / (bg_lum - blk_lum) - o * (bg_lum - org_lum) / (bg_lum - blk_lum), 0, 1)
    return o, k


def trace(alpha, min_area):
    big = cv2.resize(alpha, None, fx=UP, fy=UP, interpolation=cv2.INTER_CUBIC)
    big = cv2.GaussianBlur(big, (0, 0), UP * 0.45)
    mask = (big > 0.5).astype(np.uint8)
    contours, _ = cv2.findContours(mask, cv2.RETR_CCOMP, cv2.CHAIN_APPROX_NONE)
    polys = []
    for c in contours:
        if abs(cv2.contourArea(c)) < min_area * UP * UP:
            continue
        polys.append(cv2.approxPolyDP(c, EPS, True).reshape(-1, 2) / UP)
    return polys


def to_path(polys):
    """Polygons -> SVG path data ("M x y L x y x y ... Z" per subpath)."""
    out = []
    for poly in polys:
        pts = [f"{x:.1f} {y:.1f}".replace(".0 ", " ").removesuffix(".0") for x, y in poly]
        out.append("M" + pts[0] + "L" + " ".join(pts[1:]) + "Z")
    return "".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--preview")
    args = ap.parse_args()

    rgb = np.asarray(Image.open(SRC).convert("RGB"))
    layers = {}
    for name, box in (("mark", MARK_BOX), ("word", WORD_BOX)):
        x0, y0, x1, y1 = box
        o, k = alphas(rgb[y0:y1, x0:x1])
        layers[name] = {
            "w": x1 - x0,
            "h": y1 - y0,
            "orange": to_path(trace(o, 40)) if name == "mark" else "",
            "dark": to_path(trace(k, 40)),
        }

    m, w = layers["mark"], layers["word"]
    ts = f"""// Generated by tools/trace_logo.py from brand-source/orvelle-logo.jpg. Do not edit by hand.
// Paths use fill-rule="evenodd" (holes are separate subpaths).

export const LOGO_ORANGE = "#BF5110";

export const LOGO_MARK = {{
  width: {m["w"]},
  height: {m["h"]},
  orange: "{m["orange"]}",
  dark: "{m["dark"]}",
}} as const;

export const LOGO_WORD = {{
  width: {w["w"]},
  height: {w["h"]},
  dark: "{w["dark"]}",
}} as const;
"""
    with open(OUT, "w", newline="\n") as f:
        f.write(ts)
    print(f"wrote {OUT} ({len(ts) / 1024:.1f} KB)")

    if args.preview:
        # rasterise the polygons back for a visual check (dark layer black, orange layer orange)
        scale = 2
        def render(layer, path, color, canvas):
            for sub in path.split("Z"):
                if not sub:
                    continue
                nums = sub.replace("M", "").replace("L", " ").split()
                pts = (np.array(nums, dtype=np.float32).reshape(-1, 2) * scale).astype(np.int32)
                tmp = np.zeros(canvas.shape[:2], np.uint8)
                cv2.fillPoly(tmp, [pts], 1)
                layer ^= tmp
            canvas[layer.astype(bool)] = color
        imgs = []
        for name in ("mark", "word"):
            L = layers[name]
            canvas = np.full((L["h"] * scale, L["w"] * scale, 3), (210, 236, 248), np.uint8)
            if L["orange"]:
                render(np.zeros(canvas.shape[:2], np.uint8), L["orange"], (16, 81, 191), canvas)
            render(np.zeros(canvas.shape[:2], np.uint8), L["dark"], (21, 22, 23), canvas)
            imgs.append(canvas)
        width = max(i.shape[1] for i in imgs)
        imgs = [cv2.copyMakeBorder(i, 10, 10, 0, width - i.shape[1], cv2.BORDER_CONSTANT, value=(255, 255, 255)) for i in imgs]
        cv2.imwrite(args.preview, np.vstack(imgs))
        print(f"preview -> {args.preview}")


if __name__ == "__main__":
    main()
